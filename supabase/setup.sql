create extension if not exists pgcrypto;

create table if not exists public.aarambh_questions (
  id integer generated by default as identity primary key,
  question_text text not null,
  options jsonb not null,
  correct_option_id text not null,
  is_active boolean not null default true
);

create table if not exists public.aarambh_attempts (
  id uuid primary key default gen_random_uuid(),
  student_name text not null,
  roll_number text not null,
  branch text not null,
  exam_date date not null,
  started_at timestamptz not null default now(),
  deadline_at timestamptz not null,
  submitted_at timestamptz,
  auto_submitted boolean not null default false,
  score integer,
  correct_count integer,
  answered_count integer,
  answers jsonb,
  created_at timestamptz not null default now()
);

create unique index if not exists aarambh_one_attempt_per_roll
  on public.aarambh_attempts (lower(trim(roll_number)));

create table if not exists public.aarambh_private_config (
  key text primary key,
  value text not null
);

