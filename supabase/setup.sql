create or replace function public.get_aarambh_questions()
returns table (id integer, question_text text, options jsonb)
language sql
security definer
set search_path = public
as $$
  select q.id, q.question_text, q.options
  from public.aarambh_questions q
  where q.is_active = true
  order by q.id;
$$;

create or replace function public.start_aarambh_exam(
  p_name text, p_roll text, p_branch text, p_exam_date date
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id uuid;
  v_start timestamptz := clock_timestamp();
  v_deadline timestamptz;
begin
  if length(trim(coalesce(p_name,''))) < 2 or length(trim(coalesce(p_roll,''))) < 1 then
    raise exception 'Enter a valid name and roll number.';
  end if;
  if p_branch not in ('EEE','ECE','CSE','ME','CE','IT','Other') then
    raise exception 'Please select a valid branch.';
  end if;
  if (select count(*) from public.aarambh_questions where is_active) <> 50 then
    raise exception 'Organizer setup must contain exactly 50 active questions.';
  end if;

  v_deadline := v_start + interval '20 minutes';
  insert into public.aarambh_attempts(student_name, roll_number, branch, exam_date, started_at, deadline_at)
  values (left(trim(p_name),100), left(trim(p_roll),40), p_branch, p_exam_date, v_start, v_deadline)
  returning id into v_id;

  return jsonb_build_object('attempt_id', v_id, 'deadline_at', v_deadline);
exception when unique_violation then
  raise exception 'This roll number has already started or submitted an attempt.';
end;
$$;

create or replace function public.submit_aarambh_exam(
  p_attempt_id uuid, p_answers jsonb, p_auto_submit boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  a public.aarambh_attempts%rowtype;
  v_correct integer := 0;
  v_answered integer := 0;
  v_score integer;
  v_clean jsonb := '[]'::jsonb;
  item jsonb;
  qid integer;
  oid text;
  correct_id text;
begin
  select * into a from public.aarambh_attempts where id = p_attempt_id for update;
  if not found then raise exception 'Exam attempt not found.'; end if;
  if a.submitted_at is not null then
    return jsonb_build_object('score',a.score,'correct_count',a.correct_count,
      'answered_count',a.answered_count,'auto_submitted',a.auto_submitted);
  end if;
  if clock_timestamp() < a.deadline_at and p_auto_submit then
    raise exception 'The exam time has not expired yet.';
  end if;

  for item in select value from jsonb_array_elements(coalesce(p_answers,'[]'::jsonb))
  loop
    begin
      qid := (item->>'question_id')::integer;
      oid := item->>'option_id';
    exception when others then
      continue;
    end;
    select correct_option_id into correct_id from public.aarambh_questions
      where id = qid and is_active = true;
    if correct_id is not null and oid is not null then
      v_answered := v_answered + 1;
      if oid = correct_id then v_correct := v_correct + 1; end if;
      v_clean := v_clean || jsonb_build_array(jsonb_build_object('question_id',qid,'option_id',oid));
    end if;
  end loop;

  -- Do not permit answers to be added after the server-side deadline.
  if clock_timestamp() >= a.deadline_at then
    p_auto_submit := true;
  end if;
  v_score := v_correct;
  update public.aarambh_attempts
    set submitted_at = clock_timestamp(), auto_submitted = p_auto_submit,
        score = v_score, correct_count = v_correct, answered_count = v_answered, answers = v_clean
    where id = p_attempt_id;

  return jsonb_build_object('score',v_score,'correct_count',v_correct,
    'answered_count',v_answered,'auto_submitted',p_auto_submit);
end;
$$;

create or replace function public.admin_aarambh_results(p_password text)
returns table (
  attempt_id uuid, student_name text, roll_number text, branch text, exam_date date,
  started_at timestamptz, submitted_at timestamptz, auto_submitted boolean,
  score integer, total_questions integer, correct_count integer, answered_count integer
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_password text;
begin
  select value into v_password from public.aarambh_private_config where key = 'admin_password';
  if v_password is null or p_password is distinct from v_password then
    raise exception 'Incorrect organizer password.';
  end if;
  return query
    select a.id, a.student_name, a.roll_number, a.branch, a.exam_date,
      a.started_at, a.submitted_at, a.auto_submitted, a.score, 50, a.correct_count, a.answered_count
    from public.aarambh_attempts a
    order by a.submitted_at desc nulls last, a.started_at desc;
end;
$$;

create or replace function public.admin_aarambh_questions(p_password text)
returns table (id integer, question_text text, options jsonb, correct_option_id text)
language plpgsql
security definer
set search_path = public
as $$
declare v_password text;
begin
  select value into v_password from public.aarambh_private_config where key = 'admin_password';
  if v_password is null or p_password is distinct from v_password then
    raise exception 'Incorrect organizer password.';
  end if;
  return query select q.id, q.question_text, q.options, q.correct_option_id
    from public.aarambh_questions q where q.is_active = true order by q.id;
end;
$$;

create or replace function public.admin_save_aarambh_questions(p_password text, p_questions jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_password text;
  item jsonb;
  opt jsonb;
  v_id integer;
  v_text text;
  v_options jsonb;
  v_correct text;
  v_count integer := 0;
  v_opt_count integer;
begin
  select value into v_password from public.aarambh_private_config where key = 'admin_password';
  if v_password is null or p_password is distinct from v_password then
    raise exception 'Incorrect organizer password.';
  end if;
  if jsonb_typeof(p_questions) <> 'array' or jsonb_array_length(p_questions) <> 50 then
    raise exception 'Exactly 50 questions must be saved at once.';
  end if;

  for item in select value from jsonb_array_elements(p_questions)
  loop
    v_id := (item->>'id')::integer;
    v_text := trim(coalesce(item->>'question_text',''));
    v_options := item->'options';
    v_correct := item->>'correct_option_id';
    if v_text = '' then raise exception 'Question text cannot be empty.'; end if;
    if jsonb_typeof(v_options) <> 'array' or jsonb_array_length(v_options) <> 4 then
      raise exception 'Each question must have exactly four options.';
    end if;
    v_opt_count := 0;
    for opt in select value from jsonb_array_elements(v_options)
    loop
      v_opt_count := v_opt_count + 1;
      if trim(coalesce(opt->>'label','')) = '' then raise exception 'Option labels cannot be empty.'; end if;
      if coalesce(opt->>'id','') not in ('A','B','C','D') then raise exception 'Option IDs must be A, B, C and D.'; end if;
    end loop;
    if v_opt_count <> 4 or not (v_options @> jsonb_build_array(jsonb_build_object('id',v_correct))) then
      -- The containment check can be strict depending on option JSON shape; use explicit existence below.
      if not exists (select 1 from jsonb_array_elements(v_options) x where x->>'id' = v_correct) then
        raise exception 'Correct answer must match one of the four options.';
      end if;
    end if;
    update public.aarambh_questions
      set question_text = v_text, options = v_options, correct_option_id = v_correct
      where id = v_id and is_active = true;
    if not found then raise exception 'Question ID % was not found.', v_id; end if;
    v_count := v_count + 1;
  end loop;
  if v_count <> 50 then raise exception 'All 50 questions must be updated.'; end if;
  return jsonb_build_object('saved',true,'count',v_count);
end;
$$;

